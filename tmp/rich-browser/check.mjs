import { chromium } from './node_modules/playwright/index.mjs'
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.goto('http://localhost:5187/tmp/rich-browser/harness.html')
await page.getByRole('textbox', { name: 'Body', exact: true }).waitFor()
await page.getByRole('button', { name: 'Bold', exact: true }).click()
await page.getByRole('textbox', { name: 'Body', exact: true }).pressSequentially('Bold body')
await page.getByRole('button', { name: 'Bold', exact: true }).click()
await page.getByRole('textbox', { name: 'Body', exact: true }).pressSequentially(' normal text')
await page.getByRole('textbox', { name: 'Body', exact: true }).press('Enter')
await page.getByRole('button', { name: 'Insert table', exact: true }).click()
await page.locator('.tiptap th').first().click()
await page.keyboard.type('Header')
await page.getByRole('button', { name: 'Add row', exact: true }).click()
if (await page.locator('.tiptap tr').count() !== 4) throw new Error('Add row did not work')
await page.getByLabel('Left margin', { exact: true }).selectOption('1')
await page.getByLabel('Name of recipient', { exact: true }).fill('Recipient')
await page.getByLabel('Position / office', { exact: true }).fill('Director')
await page.getByLabel('Name of institution or office 1', { exact: true }).fill('College')
await page.getByLabel('Subject', { exact: true }).fill('Rich body test')
await page.getByLabel('Date', { exact: true }).fill('2026-09-30')
await page.screenshot({ path: 'tmp/rich-browser/editor.png', fullPage: true })
await page.getByRole('button', { name: 'Create document', exact: true }).click()
await page.waitForFunction(() => window.savedBody)
const data = await page.evaluate(() => window.savedBody)
if (!data.bodyRich.content[0].content[0].marks.some(mark => mark.type === 'bold')) throw new Error('Bold not saved')
if (data.bodyRich.attrs.marginLeft !== 1) throw new Error('Margin not saved')
if (!data.bodyRich.content.some(node => node.type === 'table')) throw new Error('Table not saved')
if (errors.length) throw new Error(errors.join('\n'))
console.log('PASS: toolbar, text entry, table editing, margins and form submission; no browser errors')
await browser.close()
